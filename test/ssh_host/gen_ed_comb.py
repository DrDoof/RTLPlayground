#!/usr/bin/env python3
"""Generate the public 4-column, 64-row Ed25519 comb table reproducibly."""
from pathlib import Path
from crypto_validate import B, P, D, add

def generate():
    bases=[B]
    for _ in range(3):
        q=bases[-1]
        for _ in range(64): q=add(q,q)
        bases.append(q)
    text=['/* Generated by test/ssh_host/gen_ed_comb.py; public points only. */',
          '/* Entry j = sum(bit(j,k) * [2^(64*k)]B), stored y-x, y+x, 2*d*x*y. */',
          'static __code const uint8_t ed_comb[16][96] = {']
    for digit in range(16):
        q=(0,1)
        for k,b in enumerate(bases):
            if digit>>k&1: q=add(q,b)
        x,y=q
        assert (-x*x+y*y-1-D*x*x*y*y)%P==0
        data=b''.join((v%P).to_bytes(32,'little') for v in (y-x,y+x,2*D*x*y))
        text.append('\t{ /* %d */'%digit)
        for i in range(0,96,8): text.append('\t\t'+', '.join('0x%02x'%v for v in data[i:i+8])+',')
        text.append('\t},')
    text.append('};')
    return '\n'.join(text)+'\n'
if __name__=='__main__':
    Path(__file__).resolve().parents[2].joinpath('crypto/ed25519_comb.h').write_text(generate())
